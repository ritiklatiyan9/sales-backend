import test from 'node:test';
import assert from 'node:assert/strict';
import { PGlite } from '@electric-sql/pglite';
import { createClientInvitationService } from './clientInvitation.service.js';
import { createClientPortalService } from './clientPortal.service.js';
import { migrateClientInvitations } from '../migrations/046_client_invitations.js';

process.env.CLIENT_PORTAL_IDENTITY_SECRET = 'test-only-stable-identity-secret';
process.env.CLIENT_PORTAL_SECRET = 'test-only-client-portal-signing-secret';
const inviteCode = 'ABCDefgh01234567_-qwerty';
test('office invitation is verified, expiring, one-use and binds exact eligible identities', async t => {
  const raw = new PGlite();
  const query = (sql,args) => raw.query(sql,args);
  const db = { query, connect: async () => ({ query, release() {} }) };
  await raw.exec(`CREATE TABLE members(id integer primary key,site_id integer,full_name text,phone text,aadhar_no text,member_type text,member_types text[],is_active boolean DEFAULT true,email text,pan_no text);
    CREATE TABLE sites(id integer primary key,name text,code text);
    CREATE TABLE kyc_cases(id integer primary key,client_member_id integer,site_id integer,status text);
    CREATE TABLE booking_client_accounts(id serial primary key,phone text,identity_key text,password_hash text,password_changed boolean DEFAULT false,token_version integer DEFAULT 0,is_active boolean DEFAULT true,aadhaar_last4 text,updated_at timestamptz DEFAULT now(),UNIQUE(phone,identity_key));
    CREATE TABLE booking_client_members(account_id integer,member_id integer UNIQUE);
    INSERT INTO sites VALUES(1,'One','ONE'),(2,'Two','TWO');
    INSERT INTO members(id,site_id,full_name,phone,aadhar_no,member_type) VALUES(1,1,'Owner','9876500001','234567890123','CLIENT'),(2,2,'Owner','9876500001','234567890123','CLIENT'),(3,1,'Other','9876500001','345678901234','CLIENT'),(4,1,'Other phone','9876500002','234567890123','CLIENT'),(5,1,'Unverified','9876500001','234567890123','CLIENT');
    INSERT INTO kyc_cases VALUES(1,1,1,'VERIFIED'),(2,2,2,'VERIFIED'),(3,3,1,'VERIFIED'),(4,4,1,'VERIFIED'),(5,5,1,'OPEN');`);
  await migrateClientInvitations(db);
  t.after(() => raw.close());
  let time = new Date('2026-10-28T00:00:00.000Z');
  const service = createClientInvitationService(db, { now: () => time, generateCode: () => inviteCode });
  const portal = createClientPortalService(db);
  await assert.rejects(service.issue({ memberId:1, issuedBy:1, identityVerified:false }), { statusCode:400 });
  assert.equal(await portal.authenticate('9876500001','234567890123'), null);
  const issued = await service.issue({ memberId:1, issuedBy:1, identityVerified:true });
  assert.equal(issued.code, inviteCode);
  const row = (await query('SELECT * FROM booking_client_invitations')).rows[0];
  assert.notEqual(row.code_hash, inviteCode);
  assert.equal(new Date(row.expires_at).getTime() - time.getTime(), 24*60*60*1000);
  await assert.rejects(service.activate({ mobile:'9876500002',code:inviteCode,newPassword:'Owner-new-password-1' }), { statusCode:401 });
  await assert.rejects(service.activate({ mobile:'9876500001',code:inviteCode,newPassword:'234567890123' }), { statusCode:401 });
  await service.activate({ mobile:'9876500001',code:inviteCode,newPassword:'Owner-new-password-1' });
  await assert.rejects(service.activate({ mobile:'9876500001',code:inviteCode,newPassword:'Another-new-password' }), { statusCode:401 });
  const account = await portal.authenticate('9876500001','Owner-new-password-1', {dryRun:true});
  assert.deepEqual(account.members.map(item => item.member_id), [1,2]);
  assert.equal(await portal.authenticate('9876500001','234567890123'), null);
  await assert.rejects(service.issue({ memberId:1, issuedBy:1, identityVerified:true }), { statusCode:409 });
  const second = createClientInvitationService(db, { now: () => time, generateCode: () => 'zyxwvuts9876543210ABCDEF' });
  const otherInvite = await second.issue({ memberId:3, issuedBy:1, identityVerified:true });
  await assert.rejects(service.activate({ mobile:'9876500001',code:otherInvite.code,newPassword:'Owner-new-password-1' }), { statusCode:400 });
  assert.equal((await portal.authenticate('9876500001','Owner-new-password-1', {dryRun:true})).account.id, account.account.id);
  await service.activate({ mobile:'9876500001',code:otherInvite.code,newPassword:'Other-password-123' });
  assert.ok(await portal.authenticate('9876500001','Other-password-123', {dryRun:true}));
  const third = createClientInvitationService(db, { now: () => time, generateCode: () => '123456789012345678901234' });
  const expired = await third.issue({ memberId:4, issuedBy:1, identityVerified:true });
  time = new Date(time.getTime()+24*60*60*1000);
  await assert.rejects(third.activate({ mobile:'9876500002',code:expired.code,newPassword:'Other-password-123' }), { statusCode:401 });
});
